-- =====================================================================
-- TBalance - PostgreSQL
-- 01. Tablas
--
-- Ejecutar conectado a la base tbalance como el usuario tbalance (pgAdmin > Query Tool, o psql -f).
-- TBalance también lo ejecuta solo la primera vez que se conecta.
--
-- Cada perfil (negocio) tiene sus propios productos, categorías,
-- proveedores, movimientos y ventas. Por eso la llave de esas tablas es
-- (PERFIL_ID, ID): el producto "1001" de una ferretería y el "1001" de una
-- droguería son productos distintos.
-- =====================================================================

CREATE TABLE PERFIL (
  ID              VARCHAR(20)  NOT NULL,
  NOMBRE          VARCHAR(100) NOT NULL,
  DESCRIPCION     VARCHAR(500),
  COLOR           VARCHAR(9),
  TIPO_NEGOCIO    VARCHAR(20),
  FECHA_CREACION  DATE,
  CONSTRAINT PK_PERFIL PRIMARY KEY (ID)
);

CREATE TABLE PERFIL_CONFIGURACION (
  PERFIL_ID  VARCHAR(20)  NOT NULL,
  CLAVE      VARCHAR(50)  NOT NULL,
  VALOR      VARCHAR(200),
  CONSTRAINT PK_PERFIL_CONFIGURACION PRIMARY KEY (PERFIL_ID, CLAVE),
  CONSTRAINT FK_CONFIGURACION_PERFIL FOREIGN KEY (PERFIL_ID)
    REFERENCES PERFIL (ID) ON DELETE CASCADE
);

CREATE TABLE CATEGORIA (
  PERFIL_ID    VARCHAR(20)  NOT NULL,
  ID           VARCHAR(30)  NOT NULL,
  NOMBRE       VARCHAR(100) NOT NULL,
  DESCRIPCION  VARCHAR(500),
  CONSTRAINT PK_CATEGORIA PRIMARY KEY (PERFIL_ID, ID),
  CONSTRAINT FK_CATEGORIA_PERFIL FOREIGN KEY (PERFIL_ID)
    REFERENCES PERFIL (ID) ON DELETE CASCADE
);

CREATE TABLE PROVEEDOR (
  PERFIL_ID  VARCHAR(20)  NOT NULL,
  ID         VARCHAR(30)  NOT NULL,
  NOMBRE     VARCHAR(100) NOT NULL,
  CONTACTO   VARCHAR(100),
  TELEFONO   VARCHAR(30),
  EMAIL      VARCHAR(100),
  DIRECCION  VARCHAR(200),
  CATEGORIA  VARCHAR(100),
  ACTIVO     SMALLINT  DEFAULT 1 NOT NULL,
  CONSTRAINT PK_PROVEEDOR PRIMARY KEY (PERFIL_ID, ID),
  CONSTRAINT FK_PROVEEDOR_PERFIL FOREIGN KEY (PERFIL_ID)
    REFERENCES PERFIL (ID) ON DELETE CASCADE,
  CONSTRAINT CK_PROVEEDOR_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE PRODUCTO (
  PERFIL_ID             VARCHAR(20)  NOT NULL,
  ID                    VARCHAR(30)  NOT NULL,
  NOMBRE                VARCHAR(150) NOT NULL,
  CODIGO                VARCHAR(60),
  DESCRIPCION           VARCHAR(500),
  CATEGORIA             VARCHAR(100),
  CATEGORIA_ID          VARCHAR(30),
  PROVEEDOR_ID          VARCHAR(30),
  PRECIO_COMPRA         NUMERIC(14,2) DEFAULT 0 NOT NULL,
  PRECIO_VENTA          NUMERIC(14,2) DEFAULT 0 NOT NULL,
  STOCK                 INTEGER      DEFAULT 0 NOT NULL,
  STOCK_MIN             INTEGER      DEFAULT 0 NOT NULL,
  TIPO                  VARCHAR(60),
  REQUIERE_VENCIMIENTO  SMALLINT     DEFAULT 0 NOT NULL,
  FECHA_VENCIMIENTO     DATE,
  FECHA_MODIFICACION    TIMESTAMP,
  CONSTRAINT PK_PRODUCTO PRIMARY KEY (PERFIL_ID, ID),
  CONSTRAINT FK_PRODUCTO_PERFIL FOREIGN KEY (PERFIL_ID)
    REFERENCES PERFIL (ID) ON DELETE CASCADE,
  CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (PERFIL_ID, CATEGORIA_ID)
    REFERENCES CATEGORIA (PERFIL_ID, ID),
  CONSTRAINT FK_PRODUCTO_PROVEEDOR FOREIGN KEY (PERFIL_ID, PROVEEDOR_ID)
    REFERENCES PROVEEDOR (PERFIL_ID, ID),
  CONSTRAINT CK_PRODUCTO_VENCE CHECK (REQUIERE_VENCIMIENTO IN (0, 1))
);

-- Movimientos y ventas guardan el ID del producto sin llave foránea a
-- PRODUCTO: son historial y deben conservarse aunque el producto se elimine
-- (la venta guarda también el nombre del producto en ese momento).

CREATE TABLE ENTRADA (
  PERFIL_ID        VARCHAR(20) NOT NULL,
  ID               VARCHAR(30) NOT NULL,
  PRODUCTO_ID      VARCHAR(30) NOT NULL,
  CANTIDAD         INTEGER      NOT NULL,
  FECHA            TIMESTAMP,
  PROVEEDOR_ID     VARCHAR(30),
  PRECIO_UNITARIO  NUMERIC(14,2) DEFAULT 0 NOT NULL,
  OBSERVACION      VARCHAR(500),
  CONSTRAINT PK_ENTRADA PRIMARY KEY (PERFIL_ID, ID),
  CONSTRAINT FK_ENTRADA_PERFIL FOREIGN KEY (PERFIL_ID)
    REFERENCES PERFIL (ID) ON DELETE CASCADE,
  CONSTRAINT CK_ENTRADA_CANTIDAD CHECK (CANTIDAD > 0)
);

CREATE TABLE SALIDA (
  PERFIL_ID    VARCHAR(20) NOT NULL,
  ID           VARCHAR(30) NOT NULL,
  PRODUCTO_ID  VARCHAR(30) NOT NULL,
  CANTIDAD     INTEGER      NOT NULL,
  FECHA        TIMESTAMP,
  MOTIVO       VARCHAR(500),
  TIPO         VARCHAR(60),
  CONSTRAINT PK_SALIDA PRIMARY KEY (PERFIL_ID, ID),
  CONSTRAINT FK_SALIDA_PERFIL FOREIGN KEY (PERFIL_ID)
    REFERENCES PERFIL (ID) ON DELETE CASCADE,
  CONSTRAINT CK_SALIDA_CANTIDAD CHECK (CANTIDAD > 0)
);

CREATE TABLE VENTA (
  PERFIL_ID        VARCHAR(20) NOT NULL,
  ID               VARCHAR(30) NOT NULL,
  CLIENTE          VARCHAR(150),
  METODO_PAGO      VARCHAR(40),
  OBSERVACION      VARCHAR(500),
  REFERENCIA_PAGO  VARCHAR(60),
  FECHA            TIMESTAMP,
  ESTADO           VARCHAR(20),
  TOTAL            NUMERIC(14,2) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_VENTA PRIMARY KEY (PERFIL_ID, ID),
  CONSTRAINT FK_VENTA_PERFIL FOREIGN KEY (PERFIL_ID)
    REFERENCES PERFIL (ID) ON DELETE CASCADE
);

CREATE TABLE DETALLE_VENTA (
  PERFIL_ID        VARCHAR(20)  NOT NULL,
  VENTA_ID         VARCHAR(30)  NOT NULL,
  LINEA            SMALLINT    NOT NULL,
  PRODUCTO_ID      VARCHAR(30)  NOT NULL,
  NOMBRE_PRODUCTO  VARCHAR(150),
  CANTIDAD         INTEGER       NOT NULL,
  PRECIO_UNITARIO  NUMERIC(14,2)  DEFAULT 0 NOT NULL,
  SUBTOTAL         NUMERIC(14,2)  DEFAULT 0 NOT NULL,
  COSTO_UNITARIO   NUMERIC(14,2)  DEFAULT 0 NOT NULL,
  CONSTRAINT PK_DETALLE_VENTA PRIMARY KEY (PERFIL_ID, VENTA_ID, LINEA),
  CONSTRAINT FK_DETALLE_VENTA FOREIGN KEY (PERFIL_ID, VENTA_ID)
    REFERENCES VENTA (PERFIL_ID, ID) ON DELETE CASCADE,
  CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0)
);

-- La llena el disparador TRG_PRODUCTO_HISTORIAL_PRECIO (02_disparadores.sql).
-- Es historial: no tiene llave foránea a PRODUCTO, igual que las ventas.
CREATE TABLE HISTORIAL_PRECIO (
  ID                      BIGINT GENERATED ALWAYS AS IDENTITY,
  PERFIL_ID               VARCHAR(20) NOT NULL,
  PRODUCTO_ID             VARCHAR(30) NOT NULL,
  PRECIO_COMPRA_ANTERIOR  NUMERIC(14,2),
  PRECIO_COMPRA_NUEVO     NUMERIC(14,2),
  PRECIO_VENTA_ANTERIOR   NUMERIC(14,2),
  PRECIO_VENTA_NUEVO      NUMERIC(14,2),
  FECHA_CAMBIO            TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
  USUARIO_BD              VARCHAR(60),
  CONSTRAINT PK_HISTORIAL_PRECIO PRIMARY KEY (ID),
  CONSTRAINT FK_HISTORIAL_PERFIL FOREIGN KEY (PERFIL_ID)
    REFERENCES PERFIL (ID) ON DELETE CASCADE
);

CREATE INDEX IX_VENTA_FECHA ON VENTA (PERFIL_ID, FECHA);
CREATE INDEX IX_HISTORIAL_PRODUCTO ON HISTORIAL_PRECIO (PERFIL_ID, PRODUCTO_ID);
