-- Borra los productos de una venta (antes de volver a escribirlos).
CREATE OR REPLACE PROCEDURE SP_BORRAR_DETALLE_VENTA (
  P_PERFIL_ID IN DETALLE_VENTA.PERFIL_ID%TYPE,
  P_VENTA_ID  IN DETALLE_VENTA.VENTA_ID%TYPE
) AS
BEGIN
  DELETE FROM DETALLE_VENTA WHERE PERFIL_ID = P_PERFIL_ID AND VENTA_ID = P_VENTA_ID;
END;
/

-- Agrega un producto (una línea) a una venta.
CREATE OR REPLACE PROCEDURE SP_AGREGAR_DETALLE_VENTA (
  P_PERFIL_ID       IN DETALLE_VENTA.PERFIL_ID%TYPE,
  P_VENTA_ID        IN DETALLE_VENTA.VENTA_ID%TYPE,
  P_LINEA           IN DETALLE_VENTA.LINEA%TYPE,
  P_PRODUCTO_ID     IN DETALLE_VENTA.PRODUCTO_ID%TYPE,
  P_NOMBRE_PRODUCTO IN DETALLE_VENTA.NOMBRE_PRODUCTO%TYPE,
  P_CANTIDAD        IN DETALLE_VENTA.CANTIDAD%TYPE,
  P_PRECIO_UNITARIO IN DETALLE_VENTA.PRECIO_UNITARIO%TYPE,
  P_SUBTOTAL        IN DETALLE_VENTA.SUBTOTAL%TYPE,
  P_COSTO_UNITARIO  IN DETALLE_VENTA.COSTO_UNITARIO%TYPE
) AS
BEGIN
  INSERT INTO DETALLE_VENTA (PERFIL_ID, VENTA_ID, LINEA, PRODUCTO_ID, NOMBRE_PRODUCTO,
                             CANTIDAD, PRECIO_UNITARIO, SUBTOTAL, COSTO_UNITARIO)
  VALUES (P_PERFIL_ID, P_VENTA_ID, P_LINEA, P_PRODUCTO_ID, P_NOMBRE_PRODUCTO,
          P_CANTIDAD, P_PRECIO_UNITARIO, P_SUBTOTAL, P_COSTO_UNITARIO);
END;
/

-- Quita los tipos de producto que trae un proveedor (antes de volver a escribirlos).
CREATE OR REPLACE PROCEDURE SP_BORRAR_TIPOS_PROVEEDOR (
  P_PERFIL_ID    IN PROVEEDOR_CATEGORIA.PERFIL_ID%TYPE,
  P_PROVEEDOR_ID IN PROVEEDOR_CATEGORIA.PROVEEDOR_ID%TYPE
) AS
BEGIN
  DELETE FROM PROVEEDOR_CATEGORIA WHERE PERFIL_ID = P_PERFIL_ID AND PROVEEDOR_ID = P_PROVEEDOR_ID;
END;
/

-- Anota que un proveedor trae productos de una categoría.
CREATE OR REPLACE PROCEDURE SP_AGREGAR_TIPO_PROVEEDOR (
  P_PERFIL_ID    IN PROVEEDOR_CATEGORIA.PERFIL_ID%TYPE,
  P_PROVEEDOR_ID IN PROVEEDOR_CATEGORIA.PROVEEDOR_ID%TYPE,
  P_CATEGORIA_ID IN PROVEEDOR_CATEGORIA.CATEGORIA_ID%TYPE
) AS
BEGIN
  INSERT INTO PROVEEDOR_CATEGORIA (PERFIL_ID, PROVEEDOR_ID, CATEGORIA_ID)
  VALUES (P_PERFIL_ID, P_PROVEEDOR_ID, P_CATEGORIA_ID);
END;
/

-- Quita los negocios a los que entra una persona (antes de volver a escribirlos).
CREATE OR REPLACE PROCEDURE SP_BORRAR_ACCESOS (
  P_USUARIO_ID IN NEGOCIO_USUARIO.USUARIO_ID%TYPE
) AS
BEGIN
  DELETE FROM NEGOCIO_USUARIO WHERE USUARIO_ID = P_USUARIO_ID;
END;
/

-- Da acceso a una persona a un negocio con un rol (DUENO, ADMINISTRADOR o CAJERO).
CREATE OR REPLACE PROCEDURE SP_AGREGAR_ACCESO (
  P_USUARIO_ID IN NEGOCIO_USUARIO.USUARIO_ID%TYPE,
  P_PERFIL_ID  IN NEGOCIO_USUARIO.PERFIL_ID%TYPE,
  P_ROL        IN NEGOCIO_USUARIO.ROL%TYPE
) AS
BEGIN
  INSERT INTO NEGOCIO_USUARIO (USUARIO_ID, PERFIL_ID, ROL) VALUES (P_USUARIO_ID, P_PERFIL_ID, P_ROL);
END;
/

-- Quita los ajustes de un negocio (antes de volver a escribirlos).
CREATE OR REPLACE PROCEDURE SP_BORRAR_CONFIGURACION (
  P_PERFIL_ID IN PERFIL_CONFIGURACION.PERFIL_ID%TYPE
) AS
BEGIN
  DELETE FROM PERFIL_CONFIGURACION WHERE PERFIL_ID = P_PERFIL_ID;
END;
/

-- Guarda un ajuste de un negocio (por ejemplo, los medios de pago que acepta).
CREATE OR REPLACE PROCEDURE SP_AGREGAR_CONFIGURACION (
  P_PERFIL_ID IN PERFIL_CONFIGURACION.PERFIL_ID%TYPE,
  P_CLAVE     IN PERFIL_CONFIGURACION.CLAVE%TYPE,
  P_VALOR     IN PERFIL_CONFIGURACION.VALOR%TYPE
) AS
BEGIN
  INSERT INTO PERFIL_CONFIGURACION (PERFIL_ID, CLAVE, VALOR) VALUES (P_PERFIL_ID, P_CLAVE, P_VALOR);
END;
/

