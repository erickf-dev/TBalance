-- =============================================================================
-- TBalance - Procedimientos para guardar en Oracle (PL/SQL)
-- =============================================================================
-- Java no escribe INSERT, UPDATE ni DELETE: para guardar llama a uno de estos
-- procedimientos con CallableStatement, por ejemplo:
--   {call SP_GUARDAR_PRODUCTO(?, ?, ?, ...)}
--
-- Cada tabla principal tiene dos:
--   SP_GUARDAR_<TABLA>  agrega (P_NUEVO = 1) o cambia (P_NUEVO = 0) una fila
--   SP_BORRAR_<TABLA>   borra una fila (se usa al restaurar una copia)
-- Los parámetros usan %TYPE: tienen el mismo tipo que la columna de la tabla.
--
-- Los procedimientos no hacen COMMIT: TBalance los llama dentro de una
-- transacción y hace COMMIT si todo salió bien o ROLLBACK si algo falló.
--
-- TBalance los crea solo al conectarse (cambio v9).
-- =============================================================================

-- Guarda un negocio: P_NUEVO = 1 la agrega; P_NUEVO = 0 cambia la que ya existe.
CREATE OR REPLACE PROCEDURE SP_GUARDAR_PERFIL (
  P_NUEVO IN NUMBER,
  P_ID IN PERFIL.ID%TYPE,
  P_NOMBRE IN PERFIL.NOMBRE%TYPE,
  P_DESCRIPCION IN PERFIL.DESCRIPCION%TYPE,
  P_COLOR IN PERFIL.COLOR%TYPE,
  P_TIPO_NEGOCIO IN PERFIL.TIPO_NEGOCIO%TYPE,
  P_FECHA_CREACION IN PERFIL.FECHA_CREACION%TYPE,
  P_ACTIVO IN PERFIL.ACTIVO%TYPE
) AS
BEGIN
  IF P_NUEVO = 1 THEN
    INSERT INTO PERFIL (ID, NOMBRE, DESCRIPCION, COLOR, TIPO_NEGOCIO, FECHA_CREACION, ACTIVO)
    VALUES (P_ID, P_NOMBRE, P_DESCRIPCION, P_COLOR, P_TIPO_NEGOCIO, P_FECHA_CREACION, P_ACTIVO);
  ELSE
    UPDATE PERFIL
       SET NOMBRE = P_NOMBRE,
           DESCRIPCION = P_DESCRIPCION,
           COLOR = P_COLOR,
           TIPO_NEGOCIO = P_TIPO_NEGOCIO,
           FECHA_CREACION = P_FECHA_CREACION,
           ACTIVO = P_ACTIVO
     WHERE ID = P_ID;
    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(-20190, 'No se encontró el registro que se quería guardar. Vuelva a abrir la lista.');
    END IF;
  END IF;
END;
/

-- Borra un negocio. Desde la pantalla casi nada se borra (se deshabilita o se
-- anula); se usa al restaurar una copia de seguridad.
CREATE OR REPLACE PROCEDURE SP_BORRAR_PERFIL (
  P_ID IN PERFIL.ID%TYPE
) AS
BEGIN
  DELETE FROM PERFIL WHERE ID = P_ID;
END;
