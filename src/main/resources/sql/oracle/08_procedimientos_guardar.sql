-- Guarda un abono a un fiado: P_NUEVO = 1 la agrega; P_NUEVO = 0 cambia la que ya existe.
CREATE OR REPLACE PROCEDURE SP_GUARDAR_ABONO (
  P_NUEVO IN NUMBER,
  P_PERFIL_ID IN ABONO.PERFIL_ID%TYPE,
  P_ID IN ABONO.ID%TYPE,
  P_CLIENTE_DOCUMENTO IN ABONO.CLIENTE_DOCUMENTO%TYPE,
  P_CLIENTE IN ABONO.CLIENTE%TYPE,
  P_MONTO IN ABONO.MONTO%TYPE,
  P_METODO_PAGO IN ABONO.METODO_PAGO%TYPE,
  P_REFERENCIA_PAGO IN ABONO.REFERENCIA_PAGO%TYPE,
  P_NOTA IN ABONO.NOTA%TYPE,
  P_FECHA IN ABONO.FECHA%TYPE,
  P_USUARIO_ID IN ABONO.USUARIO_ID%TYPE,
  P_REGISTRADO_POR IN ABONO.REGISTRADO_POR%TYPE,
  P_ESTADO IN ABONO.ESTADO%TYPE,
  P_FECHA_ANULACION IN ABONO.FECHA_ANULACION%TYPE,
  P_MOTIVO_ANULACION IN ABONO.MOTIVO_ANULACION%TYPE,
  P_ANULADA_POR IN ABONO.ANULADA_POR%TYPE
) AS
BEGIN
  IF P_NUEVO = 1 THEN
    INSERT INTO ABONO (PERFIL_ID, ID, CLIENTE_DOCUMENTO, CLIENTE, MONTO, METODO_PAGO, REFERENCIA_PAGO, NOTA, FECHA, USUARIO_ID, REGISTRADO_POR, ESTADO, FECHA_ANULACION, MOTIVO_ANULACION, ANULADA_POR)
    VALUES (P_PERFIL_ID, P_ID, P_CLIENTE_DOCUMENTO, P_CLIENTE, P_MONTO, P_METODO_PAGO, P_REFERENCIA_PAGO, P_NOTA, P_FECHA, P_USUARIO_ID, P_REGISTRADO_POR, P_ESTADO, P_FECHA_ANULACION, P_MOTIVO_ANULACION, P_ANULADA_POR);
  ELSE
    UPDATE ABONO
       SET CLIENTE_DOCUMENTO = P_CLIENTE_DOCUMENTO,
           CLIENTE = P_CLIENTE,
           MONTO = P_MONTO,
           METODO_PAGO = P_METODO_PAGO,
           REFERENCIA_PAGO = P_REFERENCIA_PAGO,
           NOTA = P_NOTA,
           FECHA = P_FECHA,
           USUARIO_ID = P_USUARIO_ID,
           REGISTRADO_POR = P_REGISTRADO_POR,
           ESTADO = P_ESTADO,
           FECHA_ANULACION = P_FECHA_ANULACION,
           MOTIVO_ANULACION = P_MOTIVO_ANULACION,
           ANULADA_POR = P_ANULADA_POR
     WHERE PERFIL_ID = P_PERFIL_ID AND ID = P_ID;
    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(-20190, 'No se encontró el registro que se quería guardar. Vuelva a abrir la lista.');
    END IF;
  END IF;
END;
/

-- Borra un abono a un fiado. Desde la pantalla casi nada se borra (se deshabilita o se
-- anula); se usa al restaurar una copia de seguridad.
CREATE OR REPLACE PROCEDURE SP_BORRAR_ABONO (
  P_PERFIL_ID IN ABONO.PERFIL_ID%TYPE,
  P_ID IN ABONO.ID%TYPE
) AS
BEGIN
  DELETE FROM ABONO WHERE PERFIL_ID = P_PERFIL_ID AND ID = P_ID;
END;
/

