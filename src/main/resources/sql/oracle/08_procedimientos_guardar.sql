-- Guarda una copia de seguridad (el archivo .zip va en un BLOB).
CREATE OR REPLACE PROCEDURE SP_GUARDAR_COPIA (
  P_NOMBRE    IN RESPALDO.NOMBRE%TYPE,
  P_FECHA     IN RESPALDO.FECHA%TYPE,
  P_TAMANO    IN RESPALDO.TAMANO%TYPE,
  P_CONTENIDO IN RESPALDO.CONTENIDO%TYPE
) AS
BEGIN
  INSERT INTO RESPALDO (NOMBRE, FECHA, TAMANO, CONTENIDO) VALUES (P_NOMBRE, P_FECHA, P_TAMANO, P_CONTENIDO);
END;
/

-- Borra una copia de seguridad. Devuelve en P_BORRADAS cuántas borró (0 o 1).
CREATE OR REPLACE PROCEDURE SP_BORRAR_COPIA (
  P_NOMBRE   IN  RESPALDO.NOMBRE%TYPE,
  P_BORRADAS OUT NUMBER
) AS
BEGIN
  DELETE FROM RESPALDO WHERE NOMBRE = P_NOMBRE;
  P_BORRADAS := SQL%ROWCOUNT;
END;
/

-- Sube el contador de cambios: así los otros computadores saben que deben
-- volver a leer los datos.
CREATE OR REPLACE PROCEDURE SP_ANOTAR_CAMBIO (
  P_CLAVE IN CAMBIO_VERSION.CLAVE%TYPE
) AS
BEGIN
  UPDATE CAMBIO_VERSION SET VERSION = VERSION + 1 WHERE CLAVE = P_CLAVE;
END;
/
