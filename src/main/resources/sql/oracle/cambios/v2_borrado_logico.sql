CREATE TABLE ESQUEMA_VERSION (
  VERSION  NUMBER(4) NOT NULL,
  FECHA    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_ESQUEMA_VERSION PRIMARY KEY (VERSION)
);

-- Borrado lógico: negocios, categorías y productos se deshabilitan (PROVEEDOR ya tenía ACTIVO)
ALTER TABLE PERFIL ADD (ACTIVO NUMBER(1) DEFAULT 1 NOT NULL);
ALTER TABLE PERFIL ADD CONSTRAINT CK_PERFIL_ACTIVO CHECK (ACTIVO IN (0, 1));
ALTER TABLE CATEGORIA ADD (ACTIVO NUMBER(1) DEFAULT 1 NOT NULL);
ALTER TABLE CATEGORIA ADD CONSTRAINT CK_CATEGORIA_ACTIVO CHECK (ACTIVO IN (0, 1));
ALTER TABLE PRODUCTO ADD (ACTIVO NUMBER(1) DEFAULT 1 NOT NULL);
ALTER TABLE PRODUCTO ADD CONSTRAINT CK_PRODUCTO_ACTIVO CHECK (ACTIVO IN (0, 1));

-- Ventas, entradas y salidas se anulan (quedan en el historial con fecha y motivo)
ALTER TABLE VENTA ADD (FECHA_ANULACION TIMESTAMP, MOTIVO_ANULACION VARCHAR2(300 CHAR));
ALTER TABLE ENTRADA ADD (
  ESTADO            VARCHAR2(20 CHAR) DEFAULT 'COMPLETADA' NOT NULL,
  FECHA_REGISTRO    TIMESTAMP,
  FECHA_ANULACION   TIMESTAMP,
  MOTIVO_ANULACION  VARCHAR2(300 CHAR));
ALTER TABLE SALIDA ADD (
  ESTADO            VARCHAR2(20 CHAR) DEFAULT 'COMPLETADA' NOT NULL,
  FECHA_REGISTRO    TIMESTAMP,
  FECHA_ANULACION   TIMESTAMP,
  MOTIVO_ANULACION  VARCHAR2(300 CHAR));
ALTER TABLE ENTRADA ADD CONSTRAINT CK_ENTRADA_ESTADO CHECK (ESTADO IN ('COMPLETADA', 'ANULADA'));
ALTER TABLE SALIDA ADD CONSTRAINT CK_SALIDA_ESTADO CHECK (ESTADO IN ('COMPLETADA', 'ANULADA'));

-- Tipos de producto que surte cada proveedor (relación muchos a muchos con CATEGORIA)
CREATE TABLE PROVEEDOR_CATEGORIA (
  PERFIL_ID     VARCHAR2(20 CHAR) NOT NULL,
  PROVEEDOR_ID  VARCHAR2(30 CHAR) NOT NULL,
  CATEGORIA_ID  VARCHAR2(30 CHAR) NOT NULL,
  CONSTRAINT PK_PROVEEDOR_CATEGORIA PRIMARY KEY (PERFIL_ID, PROVEEDOR_ID, CATEGORIA_ID),
  CONSTRAINT FK_PROVCAT_PROVEEDOR FOREIGN KEY (PERFIL_ID, PROVEEDOR_ID)
    REFERENCES PROVEEDOR (PERFIL_ID, ID) ON DELETE CASCADE,
  CONSTRAINT FK_PROVCAT_CATEGORIA FOREIGN KEY (PERFIL_ID, CATEGORIA_ID)
    REFERENCES CATEGORIA (PERFIL_ID, ID) ON DELETE CASCADE
);

-- Copias de seguridad guardadas dentro de la base (el .zip de los datos en un BLOB)
CREATE TABLE RESPALDO (
  NOMBRE     VARCHAR2(120 CHAR) NOT NULL,
  FECHA      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  TAMANO     NUMBER(12) NOT NULL,
  CONTENIDO  BLOB NOT NULL,
  CONSTRAINT PK_RESPALDO PRIMARY KEY (NOMBRE)
);
