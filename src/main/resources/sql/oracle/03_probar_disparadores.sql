-- 03. Probar los dos disparadores (opcional)
--
-- Ejecutar como TBALANCE con F5. Crea un negocio de prueba, muestra lo que
-- hace cada disparador y al final deshace todo con ROLLBACK.
-- =====================================================================

SET SERVEROUTPUT ON

INSERT INTO PERFIL (ID, NOMBRE, TIPO_NEGOCIO, FECHA_CREACION)
VALUES ('PRUEBA', 'Negocio de prueba', 'FERRETERIA', SYSDATE);

INSERT INTO PRODUCTO (PERFIL_ID, ID, NOMBRE, PRECIO_COMPRA, PRECIO_VENTA, STOCK, STOCK_MIN)
VALUES ('PRUEBA', '1', 'Martillo de uña 16 oz', 18000, 25000, 10, -3);

-- TRG_PRODUCTO_VALIDAR dejó STOCK_MIN en 0 y llenó FECHA_MODIFICACION
SELECT ID, NOMBRE, STOCK, STOCK_MIN, FECHA_MODIFICACION
FROM PRODUCTO WHERE PERFIL_ID = 'PRUEBA';

-- TRG_PRODUCTO_HISTORIAL_PRECIO: dos cambios de precio y uno sin cambio
UPDATE PRODUCTO SET PRECIO_COMPRA = 19500, PRECIO_VENTA = 27000
WHERE PERFIL_ID = 'PRUEBA' AND ID = '1';
UPDATE PRODUCTO SET PRECIO_VENTA = 28500
WHERE PERFIL_ID = 'PRUEBA' AND ID = '1';
UPDATE PRODUCTO SET PRECIO_VENTA = 28500, STOCK = 8
WHERE PERFIL_ID = 'PRUEBA' AND ID = '1';

-- Deben salir 2 filas (el tercer UPDATE no cambió precios)
SELECT PRECIO_COMPRA_ANTERIOR, PRECIO_COMPRA_NUEVO,
       PRECIO_VENTA_ANTERIOR, PRECIO_VENTA_NUEVO, FECHA_CAMBIO, USUARIO_BD
FROM HISTORIAL_PRECIO WHERE PERFIL_ID = 'PRUEBA' ORDER BY ID;

-- TRG_PRODUCTO_VALIDAR rechaza el stock negativo (ORA-20001)
BEGIN
  UPDATE PRODUCTO SET STOCK = -2 WHERE PERFIL_ID = 'PRUEBA' AND ID = '1';
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Rechazado: ' || SQLERRM);
END;
/

ROLLBACK;
