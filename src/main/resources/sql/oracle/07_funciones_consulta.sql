-- =============================================================================
-- TBalance - Funciones de consulta en Oracle (PL/SQL)
-- =============================================================================
-- Java no escribe consultas SELECT: para leer datos llama a una de estas
-- funciones. Las que devuelven filas devuelven un cursor (SYS_REFCURSOR); las
-- demás, un número.
--
-- Java las llama con CallableStatement, por ejemplo:
--   {? = call FN_LISTAR_PRODUCTOS(?)}
-- Se pueden probar en SQL Developer, conectado como TBALANCE:
--   SELECT FN_CONTAR_NEGOCIOS FROM DUAL;
--   VARIABLE c REFCURSOR
--   EXEC :c := FN_LISTAR_PRODUCTOS('1');
--   PRINT c
--
-- TBalance las crea solo al conectarse (cambio v9). Solo crean funciones: no
-- cambian tablas ni datos.
-- =============================================================================

-- Todos los negocios.
CREATE OR REPLACE FUNCTION FN_LISTAR_PERFILES RETURN SYS_REFCURSOR AS
  C SYS_REFCURSOR;
BEGIN
  OPEN C FOR SELECT * FROM PERFIL ORDER BY LENGTH(ID), ID;
  RETURN C;
END;
/

-- Ajustes de todos los negocios (medios de pago, cuentas...).
CREATE OR REPLACE FUNCTION FN_LISTAR_CONFIGURACION RETURN SYS_REFCURSOR AS
  C SYS_REFCURSOR;
BEGIN
  OPEN C FOR SELECT * FROM PERFIL_CONFIGURACION ORDER BY PERFIL_ID, CLAVE;
  RETURN C;
END;
/

