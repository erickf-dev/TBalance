-- 1 si la categoría existe en el negocio, 0 si no.
CREATE OR REPLACE FUNCTION FN_EXISTE_CATEGORIA(P_PERFIL IN VARCHAR2, P_ID IN VARCHAR2) RETURN NUMBER AS
  N NUMBER;
BEGIN
  SELECT COUNT(*) INTO N FROM CATEGORIA WHERE PERFIL_ID = P_PERFIL AND ID = P_ID;
  RETURN N;
END;
/

-- 1 si el proveedor existe en el negocio, 0 si no.
CREATE OR REPLACE FUNCTION FN_EXISTE_PROVEEDOR(P_PERFIL IN VARCHAR2, P_ID IN VARCHAR2) RETURN NUMBER AS
  N NUMBER;
BEGIN
  SELECT COUNT(*) INTO N FROM PROVEEDOR WHERE PERFIL_ID = P_PERFIL AND ID = P_ID;
  RETURN N;
END;
/

-- Cuántos negocios hay en la base.
CREATE OR REPLACE FUNCTION FN_CONTAR_NEGOCIOS RETURN NUMBER AS
  N NUMBER;
BEGIN
  SELECT COUNT(*) INTO N FROM PERFIL;
  RETURN N;
END;
/

-- Contador de cambios: sube cada vez que un equipo guarda algo.
CREATE OR REPLACE FUNCTION FN_VERSION_CAMBIOS(P_CLAVE IN VARCHAR2) RETURN NUMBER AS
  N NUMBER;
BEGIN
  SELECT COALESCE(MAX(VERSION), 0) INTO N FROM CAMBIO_VERSION WHERE CLAVE = P_CLAVE;
  RETURN N;
END;
/

-- Copias de seguridad guardadas en la base (sin el archivo).
CREATE OR REPLACE FUNCTION FN_LISTAR_COPIAS RETURN SYS_REFCURSOR AS
  C SYS_REFCURSOR;
BEGIN
  OPEN C FOR SELECT NOMBRE, FECHA, TAMANO FROM RESPALDO ORDER BY FECHA DESC;
  RETURN C;
END;
/

-- 1 si hay una copia con ese nombre, 0 si no.
CREATE OR REPLACE FUNCTION FN_EXISTE_COPIA(P_NOMBRE IN VARCHAR2) RETURN NUMBER AS
  N NUMBER;
BEGIN
  SELECT COUNT(*) INTO N FROM RESPALDO WHERE NOMBRE = P_NOMBRE;
  RETURN N;
END;
/

-- El archivo de una copia de seguridad.
CREATE OR REPLACE FUNCTION FN_LEER_COPIA(P_NOMBRE IN VARCHAR2) RETURN SYS_REFCURSOR AS
  C SYS_REFCURSOR;
BEGIN
  OPEN C FOR SELECT * FROM RESPALDO WHERE NOMBRE = P_NOMBRE;
  RETURN C;
END;
/
